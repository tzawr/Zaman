const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('hengam-language') || 'en')

  useEffect(() => {
    localStorage.setItem('hengam-language', language)
    document.documentElement.lang = language === 'fa' ? 'fa' : 'en'
    document.documentElement.dir = 'ltr'
  }, [language])

  const value = useMemo(() => ({
    language,
    isRtl: language === 'fa',
    direction: language === 'fa' ? 'rtl' : 'ltr',
    setLanguage,
    toggleLanguage: () => setLanguage(prev => prev === 'fa' ? 'en' : 'fa'),
    t: (key) => translations[language]?.[key] || translations.en[key] || key,
    // Same as t(), but fills {placeholders} so sentences that mention names or
    // counts can keep natural word order in every language.
    tf: (key, params) => {
      const raw = translations[language]?.[key] || translations.en[key] || key
      return raw.replace(/\{(\w+)\}/g, (match, name) => (
        params && params[name] !== undefined ? params[name] : match
      ))
    },
  }), [language])

  return (
    <I18nContext.Provider value={value}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
